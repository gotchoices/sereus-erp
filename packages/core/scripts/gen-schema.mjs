// Turns each module's schema (docs/specs/<module>.qsql, the single source) into a TypeScript
// string constant in src/generated/schemas.ts, so the package carries it on every platform.
// catalog.qsql → CATALOG_SCHEMA, parties.qsql → PARTIES_SCHEMA, and so on.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const specs = join(here, '../../../docs/specs');
const files = readdirSync(specs).filter((f) => f.endsWith('.qsql')).sort();

let out = '// Generated by scripts/gen-schema.mjs from docs/specs/*.qsql. Do not edit.\n';
for (const file of files) {
  const name = `${file.slice(0, -'.qsql'.length).toUpperCase().replace(/[^A-Z0-9]/g, '_')}_SCHEMA`;
  out += `\n/** sApp schema body from docs/specs/${file}. */\nexport const ${name} = ${JSON.stringify(readFileSync(join(specs, file), 'utf8'))};\n`;
}
mkdirSync(join(here, '../src/generated'), { recursive: true });
writeFileSync(join(here, '../src/generated/schemas.ts'), out);
